const quotedDemoText = new Map<string, string>();
for (const [original, chinese] of demoText) {
  const quote = original.replace(/\.\s*$/, '').replace(/\s+/g, ' ').trim();
  for (const limit of [40, 50, 60, 90, 110]) {
    const clipped = quote.length > limit ? `${quote.slice(0, limit - 1).trimEnd()}…` : quote;
    quotedDemoText.set(clipped, chinese.replace(/[。.]$/, ''));
  }
}

/** Display projection only. The simulator and evidence checks keep their original data. */
export function demoChineseText(value: string): string {
  const exact = demoText.get(value) ?? generatedText.get(value) ?? quotedDemoText.get(value);
  if (exact !== undefined) return exact;

  const regenerated = /^Simulated regeneration: content carried over from v(\d+) for review against brief v(\d+|–)\. Run verification before relying on it\.$/.exec(value);
  if (regenerated) return `模拟重新生成：沿用研究 v${regenerated[1]} 的内容，供依据简报 v${regenerated[2]} 复核。使用前请先运行证据核验。`;
  const strategy = /^Simulated strategy draft generated from research v(\d+|–) and brief v(\d+|–)\. Review before use\.$/.exec(value);
  if (strategy) return `依据研究 v${strategy[1]} 和简报 v${strategy[2]} 生成的模拟策略草稿。使用前须审阅。`;
  const research = /^This research supports the brief for (.+)\. Each section below follows one objective from brief v(\d+)\.$/.exec(value);
  if (research) return `本研究支持“${demoChineseText(research[1])}”的简报。以下章节分别对应简报 v${research[2]} 的一个目标。`;
  const title = /^(Research|Strategy) — (.+)$/.exec(value);
  if (title) return `${title[1] === 'Research' ? '研究' : '策略'}：${demoChineseText(title[2])}`;
  const position = /^A positioning for (.+) that answers the brief’s first objective: (.+)$/.exec(value);
  if (position) return `“${demoChineseText(position[1])}”的定位，回应简报首项目标：${demoChineseText(position[2])}`;
  const territory = /^Territory ([A-C]): A route that answers: (.+)$/.exec(value);
  if (territory) return `方向 ${territory[1]}：回应目标“${demoChineseText(territory[2])}”。`;
  const open = /^Open: (.+)$/.exec(value);
  if (open) return `待解决：${demoChineseText(open[1])}`;
  const dimensions = /^(Landscape|Portrait|Square) image, (\d+) × (\d+) px\.$/.exec(value);
  if (dimensions) return `${dimensions[1] === 'Landscape' ? '横向' : dimensions[1] === 'Portrait' ? '纵向' : '方形'}图像，${dimensions[2]} × ${dimensions[3]} 像素。`;
  const colors = /^Dominant colours sampled in your browser: (#[\da-fA-F]{6}(?:, #[\da-fA-F]{6})*)\.$/.exec(value);
  if (colors) return `浏览器采样的主要颜色：${colors[1]}。`;

  // Strategy templates compose a known fixture heading and description into one list item.
  const separator = value.indexOf(': ');
  if (separator !== -1) {
    const name = value.slice(0, separator);
    const description = value.slice(separator + 2);
    const translatedName = demoText.get(name) ?? generatedText.get(name);
    const translatedDescription = demoText.get(description);
    if (translatedName && translatedDescription) return `${translatedName}：${translatedDescription}`;
  }
  return value;
}

/** An interpretation, never a replacement for the preserved verbatim excerpt. */
export function demoSourceChineseSummary(source: Source): string | null {
  if (!source.isSampleLink || !/^src-(luma|northline|morrow|plumtide)-/.test(source.id)) return null;
  return demoText.get(source.excerpt) ?? null;
}
